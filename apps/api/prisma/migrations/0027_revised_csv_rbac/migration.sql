CREATE FUNCTION pathways.p10_guard_evaluation_weight() RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
BEGIN
 IF current_user='pathways_runtime' AND NOT pathways.p09_can('settings.configure')
 AND to_jsonb(NEW)-ARRAY['weight_percentage','updated_at'] IS DISTINCT FROM to_jsonb(OLD)-ARRAY['weight_percentage','updated_at']
 THEN RAISE EXCEPTION 'Evaluation weight configuration cannot edit criterion definitions' USING ERRCODE='42501'; END IF;
 RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION pathways.p10_guard_evaluation_weight() FROM PUBLIC,anon,authenticated,service_role,pathways_runtime;
