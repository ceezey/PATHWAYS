-- Only a boolean needed to preserve configuration freezes; no beneficiary data.
CREATE FUNCTION pathways.p10_journey_has_events(wanted_project uuid) RETURNS boolean
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path='' AS $$
BEGIN
 IF NOT pathways.p05_has_project_permission('journeys.manage',wanted_project) THEN
   RAISE EXCEPTION 'Journey configuration unavailable' USING ERRCODE='42501'; END IF;
 RETURN EXISTS(SELECT FROM pathways.beneficiary_journey_events e WHERE e.project_id=wanted_project
 AND e.organization_id=pathways.runtime_context_organization());
END $$;
REVOKE ALL ON FUNCTION pathways.p10_journey_has_events(uuid) FROM PUBLIC,anon,authenticated,service_role;
GRANT EXECUTE ON FUNCTION pathways.p10_journey_has_events(uuid) TO pathways_runtime;

